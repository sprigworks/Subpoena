// Package invgen (cmd/subpoena-invgen) generates invariants/names.go: one string constant per
// invariants/*.traceql file, so tests reference an invariant by name
// (invariants.NoExecAfterDeny) instead of pasting its TraceQL.
package invgen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

// Names returns the invariant names (file name without .traceql) in dir, sorted.
func Names(dir string) ([]string, error) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range ents {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".traceql") {
			names = append(names, strings.TrimSuffix(e.Name(), ".traceql"))
		}
	}
	sort.Strings(names)
	return names, nil
}

// Ident turns an invariant name into an exported Go identifier:
// no_exec_after_deny -> NoExecAfterDeny. Names must be lower snake case.
func Ident(name string) (string, error) {
	if name == "" {
		return "", fmt.Errorf("invgen: empty invariant name")
	}
	var b strings.Builder
	up := true
	for _, r := range name {
		switch {
		case r == '_' || r == '-':
			up = true
		case r < unicode.MaxASCII && (unicode.IsLower(r) || unicode.IsDigit(r)):
			if up {
				r = unicode.ToUpper(r)
				up = false
			}
			b.WriteRune(r)
		default:
			return "", fmt.Errorf("invgen: invariant name %q: only lower-case ASCII, digits, '_' and '-' are allowed", name)
		}
	}
	id := b.String()
	if unicode.IsDigit(rune(id[0])) {
		return "", fmt.Errorf("invgen: invariant name %q must not start with a digit", name)
	}
	return id, nil
}

// Generate returns the source of names.go for the invariants in dir.
func Generate(dir string) ([]byte, error) {
	names, err := Names(dir)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by subpoena-invgen from *.traceql; DO NOT EDIT.\n")
	buf.WriteString("// Regenerate with `go generate` in this directory.\n\n")
	buf.WriteString("package invariants\n\n")
	buf.WriteString("// Invariant names: pass to Load or MustLoad. Every match of the query is a violation.\n")
	buf.WriteString("const (\n")
	seen := map[string]string{}
	for _, n := range names {
		id, err := Ident(n)
		if err != nil {
			return nil, err
		}
		if prev, dup := seen[id]; dup {
			return nil, fmt.Errorf("invgen: %q and %q both map to identifier %s", prev, n, id)
		}
		seen[id] = n
		fmt.Fprintf(&buf, "\t%s = %q\n", id, n)
	}
	buf.WriteString(")\n\n")
	buf.WriteString("// Names lists every embedded invariant, sorted.\n")
	buf.WriteString("func Names() []string {\n\treturn []string{\n")
	for _, n := range names {
		fmt.Fprintf(&buf, "\t\t%q,\n", n)
	}
	buf.WriteString("\t}\n}\n")
	return format.Source(buf.Bytes())
}

// Write generates names.go in dir.
func Write(dir string) error {
	src, err := Generate(dir)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "names.go"), src, 0o644)
}
